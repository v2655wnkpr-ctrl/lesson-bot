def hours_text(hours: int) -> str:
    if hours == 1:
        return "за 1 час"
    if hours == 24:
        return "за 1 день"
    if hours == 48:
        return "за 2 дня"
    if hours == 168:
        return "за неделю"
    return f"за {hours} ч."
